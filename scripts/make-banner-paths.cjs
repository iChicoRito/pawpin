// Writes src/lib/banner-paths.ts from assets/DarkMode.svg: each shape of the banner with the
// box it sits in, so the splash can move the shapes one by one. Run from the project folder: node scripts/make-banner-paths.cjs
const fs = require('node:fs');

const svg = fs.readFileSync('assets/DarkMode.svg', 'utf8');
const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1]);
if (paths.length !== 12) throw new Error(`Banner has ${paths.length} paths, expected 12`);

/** The box around a path, one unit wider on each side. Curves are sampled, which is close enough. */
function box(d) {
  const xs = [];
  const ys = [];
  let x = 0;
  let y = 0;
  for (const [, command, rest] of d.matchAll(/([A-Za-z])([^A-Za-z]*)/g)) {
    const n = (rest.match(/-?\d*\.?\d+(?:e-?\d+)?/g) ?? []).map(Number);
    if (command === 'H') x = n[0];
    else if (command === 'V') y = n[0];
    else if (command === 'M' || command === 'L') [x, y] = n.slice(-2);
    else if (command === 'C') {
      for (let i = 0; i < n.length; i += 6) {
        const [x1, y1, x2, y2, x3, y3] = n.slice(i, i + 6);
        for (let t = 0.1; t < 1; t += 0.1) {
          const u = 1 - t;
          xs.push(u * u * u * x + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t * t * t * x3);
          ys.push(u * u * u * y + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t * t * t * y3);
        }
        [x, y] = [x3, y3];
        xs.push(x);
        ys.push(y);
      }
    } else if (command !== 'Z') throw new Error(`Path command ${command} is not handled`);
    xs.push(x);
    ys.push(y);
  }
  const left = Math.floor(Math.min(...xs)) - 1;
  const top = Math.floor(Math.min(...ys)) - 1;
  return [left, top, Math.ceil(Math.max(...xs)) + 1 - left, Math.ceil(Math.max(...ys)) + 1 - top];
}

const part = (index) => ({ d: paths[index], box: box(paths[index]) });
const banner = {
  // P, a, w, P, i, n. The first three take the ink color, the rest are orange.
  letters: [0, 4, 2, 1, 5, 3].map(part),
  // The paw over the "i".
  pad: part(6),
  toes: [8, 7, 9, 10].map(part),
  tagline: part(11),
};

fs.writeFileSync(
  'src/lib/banner-paths.ts',
  `// Generated by scripts/make-banner-paths.cjs from assets/DarkMode.svg. Do not edit by hand.
// \`box\` is left, top, width, height inside the banner's 735 by 253 drawing.
export type BannerPart = { d: string; box: number[] };
export const BANNER: { letters: BannerPart[]; pad: BannerPart; toes: BannerPart[]; tagline: BannerPart } = ${JSON.stringify(banner, null, 1)};
`
);
